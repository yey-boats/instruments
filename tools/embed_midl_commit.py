#!/usr/bin/env python3
"""Stamp the pinned midl commit into the firmware.

Usage:
    python3 tools/embed_midl_commit.py          # regenerate include/midl_gen/midl_commit.h
    python3 tools/embed_midl_commit.py --check  # fail if the header is stale
    python3 tools/embed_midl_commit.py --print  # print the commit and exit

The commit is the midl submodule's checked-out HEAD when the submodule is
present, else the gitlink the superproject pins (`git rev-parse HEAD:midl`),
so the check also works in a checkout without submodules. The firmware reports
it as heartbeat `midl.commit`, identity `capabilities.midl.commit`,
`/api/midl/records` `midlCommit` and `/api/state` `device.midl_commit`.
"""

import os
import re
import subprocess
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
OUT = os.path.join(REPO_ROOT, "include", "midl_gen", "midl_commit.h")
SHA_RE = re.compile(r"^[0-9a-f]{40}$")


def _git(*args, cwd=REPO_ROOT):
    try:
        out = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip()


def midl_commit():
    sub = os.path.join(REPO_ROOT, "midl")
    if os.path.exists(os.path.join(sub, ".git")):
        sha = _git("rev-parse", "HEAD", cwd=sub)
        if sha and SHA_RE.match(sha):
            return sha
    sha = _git("rev-parse", "HEAD:midl")
    if sha and SHA_RE.match(sha):
        return sha
    raise SystemExit("cannot resolve the midl commit (no submodule checkout, no gitlink)")


def render(sha):
    return "\n".join([
        "#pragma once",
        "// AUTO-GENERATED by tools/embed_midl_commit.py - do not edit.",
        "// The midl (yey-boats/midl) commit this firmware's embedded manifests,",
        "// built-in records and editor page were generated from. Regenerate with",
        "// `make embed-midl-commit` (or `make midl-latest`).",
        "//",
        "// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0",
        "",
        "// clang-format off",
        "namespace midl_gen {",
        'inline constexpr const char *MIDL_COMMIT = "%s";' % sha,
        'inline constexpr const char *MIDL_COMMIT_SHORT = "%s";' % sha[:7],
        "}  // namespace midl_gen",
        "// clang-format on",
        "",
    ])


def main(argv):
    sha = midl_commit()
    if "--print" in argv:
        print(sha)
        return 0
    text = render(sha)
    rel = os.path.relpath(OUT, REPO_ROOT)
    if "--check" in argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("stale %s: pinned midl is %s (run `make embed-midl-commit`)" % (rel, sha))
            return 1
        print("%s up to date (midl %s)" % (rel, sha[:12]))
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (midl %s)" % (rel, sha))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
