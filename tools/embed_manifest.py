#!/usr/bin/env python3
"""Embed the MIDL capabilities manifests into per-class C++ headers.

Usage:
    python3 tools/embed_manifest.py            # every class (what CI checks)
    python3 tools/embed_manifest.py <class>... # just these

    class: square-480, landscape-800x480, landscape-1024x600, round-360

For each class writes two headers, both AUTO-GENERATED from the same
capability JSON (midl/schemas/gen/yb-midl-capabilities.<class>.json) so they
cannot drift:

  include/midl_gen/<class>/manifest.h
      constexpr const char* of the verbatim JSON, served from a web handler
      without any heap allocation.

  include/midl_gen/<class>/limits.h
      constexpr ints (maxTiles, maxDepth) parsed from the JSON's class entry,
      consumed by include/midl_limits.h so the firmware's fixed-array bounds
      (solver PlacementSet, MIDL arena, freeform tiles) are driven by the SAME
      spec the manager validates against. Single source of truth.

Which class a build uses is chosen per PlatformIO env by tools/midl_class.py
(pre: script), via include/generated_midl_manifest.h / generated_midl_limits.h
(instruments#19: every build used to embed square-480).
"""

import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)

VALID_CLASSES = ("square-480", "landscape-800x480", "landscape-1024x600", "round-360")
DELIMITER = "midljson"


def source_path(class_id):
    return os.path.join(REPO_ROOT, "midl", "schemas", "gen", f"yb-midl-capabilities.{class_id}.json")


def out_dir(class_id):
    return os.path.join(REPO_ROOT, "include", "midl_gen", class_id)


def render(class_id):
    """Return (manifest_header_text, limits_header_text) for a class."""
    if class_id not in VALID_CLASSES:
        raise ValueError(f"unknown class '{class_id}'. Valid: {', '.join(VALID_CLASSES)}")
    src = source_path(class_id)
    if not os.path.isfile(src):
        raise FileNotFoundError(f"source not found: {src}")
    with open(src, "r", encoding="utf-8") as f:
        json_text = f.read()

    # Safety check: the raw-string delimiter must not appear in the payload.
    if DELIMITER in json_text:
        raise ValueError(f"delimiter '{DELIMITER}' found inside JSON — choose a different delimiter")

    manifest_h = f"""\
#pragma once
// AUTO-GENERATED by tools/embed_manifest.py from the MIDL submodule. Do not edit.
// Source: midl/schemas/gen/yb-midl-capabilities.{class_id}.json
namespace midl_manifest {{
inline constexpr const char *CLASS_ID = "{class_id}";
inline constexpr const char *JSON = R"{DELIMITER}({json_text}){DELIMITER}";
}}  // namespace midl_manifest
"""

    manifest = json.loads(json_text)
    classes = manifest.get("classes", [])
    cls = next((c for c in classes if c.get("id") == class_id), None)
    if cls is None:
        raise ValueError(f"no '{class_id}' class entry in {src}")
    max_tiles = int(cls["maxTiles"])
    max_depth = int(cls["maxDepth"])

    limits_h = f"""\
#pragma once
// AUTO-GENERATED by tools/embed_manifest.py from the MIDL submodule. Do not edit.
// Source: midl/schemas/gen/yb-midl-capabilities.{class_id}.json
//
// These are the firmware projection bounds for the {class_id} display class,
// parsed from the SAME capability JSON that is served verbatim via
// midl_gen/{class_id}/manifest.h. include/midl_limits.h consumes them (through
// include/generated_midl_limits.h) so the solver/arena/freeform fixed-array
// sizes and the advertised manifest can never silently diverge. Regenerate
// with `make embed-manifest`.
namespace midl_gen {{
inline constexpr const char *CLASS_ID = "{class_id}";
inline constexpr int MAX_TILES = {max_tiles};
inline constexpr int MAX_DEPTH = {max_depth};
}}  // namespace midl_gen
"""
    return manifest_h, limits_h


def write_class(class_id):
    manifest_h, limits_h = render(class_id)
    d = out_dir(class_id)
    os.makedirs(d, exist_ok=True)
    for name, text in (("manifest.h", manifest_h), ("limits.h", limits_h)):
        p = os.path.join(d, name)
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"Wrote {os.path.relpath(p, REPO_ROOT)}")


def main(argv):
    targets = [a for a in argv if a != "--all"] or list(VALID_CLASSES)
    try:
        for class_id in targets:
            write_class(class_id)
    except (ValueError, FileNotFoundError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
