#!/usr/bin/env python3
"""Embed the built-in MIDL records into per-class C++ headers.

Usage:
    python3 tools/embed_builtin_records.py          # regenerate every class
    python3 tools/embed_builtin_records.py --check  # fail if a header is stale

The display renders MIDL screens only (docs/midl/midl-only.md). Every built-in
screen is an EMBEDDED RECORD: one MIDL document baked into the firmware, with
the screen id the old hand-written C++ screen had (dashboard, wind, ...), so
`screen.set <id>` keeps working.

Source of truth: midl/library/builtin/<id>.midl.json in the midl submodule (the
same files Display Manager lists as its built-in presets). File name = record
id = the id of the document's single screen.

Per display class (same mechanism as tools/embed_manifest.py: one header per
class under include/midl_gen/<class>/, selected by include/generated_midl_builtin.h
via tools/midl_class.py) a record is embedded when one of its screens declares
a `variants` entry for that class (a record that declares no variants at all
ships on every class). The doc itself is embedded unchanged.

Each doc is minified (compact JSON, key order kept, exactly what
JSON.stringify(doc) gives). The record hash is "sha256:" + sha256 of exactly
those bytes; the device reports it and Display Manager compares against it.
"""

import hashlib
import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
LIBRARY_DIR = os.path.join(REPO_ROOT, "midl", "library", "builtin")
CLASSES = ("square-480", "landscape-800x480", "landscape-1024x600", "round-360")

# Carousel order of the built-in records (= the old C++ screen order).
BUILTIN_ORDER = [
    "dashboard", "wind", "wind_classic", "wind_steer", "nav", "depth",
    "steering", "route", "autopilot", "trip", "status",
    "ap_hud", "knob_compass", "knob_wind", "knob_big",
]
DELIM = "midlrec"



def out_path(class_id):
    return os.path.join(REPO_ROOT, "include", "midl_gen", class_id, "builtin_records.h")


def sources():
    """[(record_id, path)] in carousel order."""
    if not os.path.isdir(LIBRARY_DIR):
        raise SystemExit("%s missing: git submodule update --init midl" % LIBRARY_DIR)
    files = sorted(f for f in os.listdir(LIBRARY_DIR) if f.endswith(".midl.json"))
    ids = [f[: -len(".midl.json")] for f in files]
    rank = {rid: i for i, rid in enumerate(BUILTIN_ORDER)}
    ids.sort(key=lambda rid: (rank.get(rid, len(rank)), rid))
    return [(rid, os.path.join(LIBRARY_DIR, rid + ".midl.json")) for rid in ids]


def ships_on(doc, class_id):
    classes = set()
    for s in doc.get("screens") or []:
        for v in s.get("variants") or []:
            classes.add(v.get("class"))
    return not classes or class_id in classes


def c_str(s):
    return json.dumps(s, ensure_ascii=False)


def render(class_id):
    body = []
    table = []
    i = 0
    for rid, path in sources():
        if len(rid) > 32 or not all(c.isdigit() or ("a" <= c <= "z") or c in "_-" for c in rid):
            raise SystemExit("bad record id %r" % rid)
        with open(path, "r", encoding="utf-8") as f:
            doc = json.load(f)
        if not ships_on(doc, class_id):
            continue
        mini = json.dumps(doc, ensure_ascii=False, separators=(",", ":"))
        if (")" + DELIM + '"') in mini:
            raise SystemExit("record %s contains the raw-string delimiter" % rid)
        raw = mini.encode("utf-8")
        digest = "sha256:" + hashlib.sha256(raw).hexdigest()
        screens = doc.get("screens") or []
        title = doc.get("title") or (screens[0].get("title") if screens else None) or rid
        body.append("inline constexpr char JSON_%d[] = R\"%s(%s)%s\";" % (i, DELIM, mini, DELIM))
        table.append("    {%s, %s, %s, JSON_%d, %d}," % (c_str(rid), c_str(title), c_str(digest),
                                                         i, len(raw)))
        i += 1
    lines = [
        "#pragma once",
        "// AUTO-GENERATED by tools/embed_builtin_records.py - do not edit.",
        "// Class: %s. Source: midl/library/builtin/*.midl.json." % class_id,
        "// Regenerate with `make embed-records`.",
    ]
    lines += [
        "//",
        "// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0",
        "",
        "#include <stddef.h>",
        "",
        "// clang-format off",
        "namespace midl_builtin {",
        "",
        "inline constexpr const char *CLASS_ID = %s;" % c_str(class_id),
        "",
        "struct Record {",
        "    const char *id;",
        "    const char *title;",
        "    const char *hash;  // \"sha256:<hex>\" of json[0..len)",
        "    const char *json;  // minified MIDL document",
        "    size_t len;",
        "};",
        "",
    ]
    lines += body
    lines += ["", "inline constexpr Record RECORDS[] = {"] + table + [
        "};",
        "inline constexpr size_t COUNT = sizeof(RECORDS) / sizeof(RECORDS[0]);",
        "",
        "}  // namespace midl_builtin",
        "// clang-format on",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    stale = []
    for cls in CLASSES:
        text = render(cls)
        p = out_path(cls)
        if "--check" in argv:
            cur = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
            if cur != text:
                stale.append(os.path.relpath(p, REPO_ROOT))
            continue
        with open(p, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote %s" % os.path.relpath(p, REPO_ROOT))
    if stale:
        print("stale (run `make embed-records`): " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
