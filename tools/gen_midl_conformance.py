#!/usr/bin/env python3
"""Export midl's validation conformance corpus as JSON for the native tests.

Usage:
    python3 tools/gen_midl_conformance.py           # writes the fixture
    python3 tools/gen_midl_conformance.py --check   # exit 1 if it is stale

Reads the pinned MIDL submodule:
  midl/conformance/cases.yaml     documents + targetClass (+ manifestOverrides)
  midl/conformance/expected.json  each case's frozen verdict {ok, paths}
  midl/schemas/gen/*.json         the per-class capability manifests

and writes test/fixtures/yb-midl/conformance/cases.json, which
test/test_midl_validate runs through the firmware's on-device validator
(midl::validate, instruments#20). The native test env has no YAML parser and
no submodule checkout, so the fixture is self-contained: every document is
converted to JSON (yaml.safe_load, same as midl's Python validator) and every
class manifest is included once. CI regenerates it and fails on a diff, so a
submodule bump that changes the corpus must commit the new fixture.

Requires PyYAML.
"""

import json
import os
import sys

import yaml

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
MIDL = os.path.join(REPO_ROOT, "midl")
OUT = os.path.join(REPO_ROOT, "test", "fixtures", "yb-midl", "conformance", "cases.json")


def build():
    with open(os.path.join(MIDL, "conformance", "cases.yaml"), "r", encoding="utf-8") as f:
        cases = yaml.safe_load(f)["cases"]
    with open(os.path.join(MIDL, "conformance", "expected.json"), "r", encoding="utf-8") as f:
        expected = json.load(f)
    if not cases:
        raise ValueError("midl/conformance/cases.yaml has zero cases")

    manifests = {}
    out_cases = []
    for c in cases:
        cls = c["targetClass"]
        if cls not in manifests:
            p = os.path.join(MIDL, "schemas", "gen", f"yb-midl-capabilities.{cls}.json")
            with open(p, "r", encoding="utf-8") as f:
                manifests[cls] = json.load(f)
        if "docFile" in c:
            with open(os.path.join(MIDL, c["docFile"]), "r", encoding="utf-8") as f:
                text = f.read()
        else:
            text = c["doc"]
        if c["name"] not in expected:
            raise ValueError(f"case {c['name']} has no expected verdict")
        out_cases.append({
            "name": c["name"],
            "targetClass": cls,
            "manifestOverrides": c.get("manifestOverrides") or {},
            "doc": yaml.safe_load(text),
            "expected": expected[c["name"]],
        })
    return {
        "_generated": "AUTO-GENERATED by tools/gen_midl_conformance.py from midl/conformance. Do not edit.",
        "manifests": dict(sorted(manifests.items())),
        "cases": out_cases,
    }


def render():
    return json.dumps(build(), indent=1, ensure_ascii=False, sort_keys=False) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(OUT, "r", encoding="utf-8") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print(f"{os.path.relpath(OUT, REPO_ROOT)} is stale: run python3 tools/gen_midl_conformance.py",
                  file=sys.stderr)
            return 1
        print("conformance fixture up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, REPO_ROOT)} ({len(json.loads(text)['cases'])} cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
